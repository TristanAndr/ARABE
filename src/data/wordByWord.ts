/**
 * Mot à mot : al-Fātiḥa, al-Ikhlāṣ, Āyat al-Kursī, al-Mulk et le tashahhud, mot par mot avec leur sens.
 *
 * Texte coranique : Tanzil Quran Text (Uthmani, version 1.1), © 2007-2026 Tanzil Project, CC BY 3.0,
 * https://tanzil.net. Chaque mot est copié tel quel du fichier `data/tanzil/quran-uthmani.txt`
 * (signes de pause retirés, basmala placée en tête du verset 1 laissée à al-Fātiḥa) ; un test le
 * vérifie.
 *
 * Tashahhud : version de ʿUmar rapportée dans le Muwaṭṭaʾ de l'imam Mālik (التَّحِيَّاتُ لِلَّهِ،
 * الزَّاكِيَاتُ لِلَّهِ…), en écriture courante vocalisée, découpée en cinq parties.
 *
 * Sens : traduction établie à la main, mot par mot, d'après le sens classique. Un mot qui revient
 * (اللَّه, الرَّحْمَٰن…) renvoie à une seule entrée du lexique (`key`) : il s'apprend une fois.
 * `base` regroupe les formes et les homographes d'un même mot (إِيَّاكَ et وَإِيَّاكَ, مَا « ce que » et
 * مَا « ne… pas ») : ils ne se servent pas de piège l'un à l'autre.
 */

export type WordKind = 'nom' | 'verbe' | 'pronom' | 'particule'

export interface Lemma {
  fr: string
  kind: WordKind
  /** Famille du mot (forme de base), si l'entrée n'en est qu'une forme ou un homographe. */
  base?: string
  /** Découpage du mot : [arabe, sens] de chaque morceau, dans l'ordre de lecture. */
  parts?: readonly (readonly [string, string])[]
}

export interface VerseWord {
  /** Le mot tel qu'il est écrit (muṣḥaf Tanzil pour le Coran). */
  ar: string
  /** Entrée du lexique. */
  key: string
  /** Lecture du mot, dans la phrase. */
  tr: string
}

export interface WbwVerse {
  /** Identifiant : « sourate:verset », ou « tashahhud:n » pour une partie du tashahhud. */
  id: string
  /** Sourate et verset, pour un texte coranique. */
  surah?: number
  ayah?: number
  fr: string
  words: readonly VerseWord[]
}

export interface WbwText {
  id: 'fatiha' | 'ikhlas' | 'kursi' | 'mulk' | 'tashahhud'
  title: string
  titleAr: string
  emoji: string
  verses: readonly WbwVerse[]
}

