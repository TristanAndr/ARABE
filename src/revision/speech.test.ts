import { describe, expect, it } from 'vitest'
import { pausalForm } from './speech'

describe('forme de pause', () => {
  it.each([
    ['مِشْمِشٌ', 'مِشْمِش'],
    ['مِشْمِشَةٌ', 'مِشْمِشَة'],
    ['مِشْمِشَتَانِ', 'مِشْمِشَتَان'],
    ['أَحْمَرُ', 'أَحْمَر'],
    ['حَمْرَاءُ', 'حَمْرَاء'],
    ['بُنِّيٌّ', 'بُنِّي'],
    ['بُنِّيَّةٌ', 'بُنِّيَّة'],
    ['كُمَّثْرَى', 'كُمَّثْرَى'],
    ['كِيوِي', 'كِيوِي'],
    ['شُكْرًا', 'شُكْرَا'],
    ['حَبَّةُ فَرَاوِلَةٍ', 'حَبَّةُ فَرَاوِلَة'],
    ['حَبَّتَا كِيوِي', 'حَبَّتَا كِيوِي'],
  ])('%s → %s', (word, pausal) => {
    expect(pausalForm(word)).toBe(pausal.normalize('NFC'))
  })
})
